// strip accidental non-emoji tokens (defensive — keeps picker clean if a bad literal slips in)
const clean = (arr: string[]) => arr.filter((e) => /\p{Extended_Pictographic}|[#*0-9]️?⃣/u.test(e))

export function EmojiPicker({ onPick, onClose }: { onPick: (emoji: string) => void; onClose: () => void }) {
  const [cat, setCat] = useState(CATEGORIES[0].key)
  const ref = useRef<HTMLDivElement>(null)

  useEffect(() => {
    const onDoc = (e: MouseEvent) => { if (ref.current && !ref.current.contains(e.target as Node)) onClose() }
    document.addEventListener('mousedown', onDoc)
    return () => document.removeEventListener('mousedown', onDoc)
  }, [onClose])

  const current = CATEGORIES.find((c) => c.key === cat) ?? CATEGORIES[0]

  return (
    <div className="emoji-picker" ref={ref} dir="rtl">
      <div className="emoji-picker__tabs">
        {CATEGORIES.map((c) => (
          <button
            key={c.key} type="button" title={c.label}
            className={`emoji-picker__tab ${cat === c.key ? 'on' : ''}`}
            onClick={() => setCat(c.key)}
          >
            {c.icon}
          </button>
        ))}
      </div>
      <div className="emoji-picker__grid">
        {clean(current.emojis).map((e) => (
          <button key={e} type="button" className="emoji-picker__item" onClick={() => onPick(e)}>{e}</button>
        ))}
      </div>
    </div>
  )
}
