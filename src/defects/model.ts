/** Short defect-log item label: "1. 🛡️ העוגנים במקום ותקינים" style (hidden רשימות sheet).
 *  Derived from the full item text: number + text up to the first " — " separator. */
export function defectItemLabel(gate: GateKey, itemNo: number): string {
  const item = GATES[gate].items.find((i) => i.no === itemNo)
  if (!item) return String(itemNo)
  const cut = item.text.split(' — ')[0]
  return `${item.no}. ${cut}`
}
